package com.example.gallery.domain.model

import androidx.room.Entity
import androidx.room.PrimaryKey
import androidx.room.Index
import kotlinx.datetime.LocalDateTime
import kotlinx.serialization.Serializable

/**
 * Core media item model - optimized for Android Go (lightweight)
 */
@Entity(
    tableName = "media_items",
    indices = [
        Index(value = ["dateTaken"], name = "idx_date_taken"),
        Index(value = ["bucketId"], name = "idx_bucket_id"),
        Index(value = ["isFavorite"], name = "idx_favorite"),
        Index(value = ["mimeType"], name = "idx_mime_type"),
        Index(value = ["locationLat", "locationLng"], name = "idx_location"),
    ]
)
@Serializable
data class MediaItem(
    @PrimaryKey val id: Long,
    val bucketId: Long,
    val bucketDisplayName: String,
    val displayName: String,
    val mimeType: String,
    val width: Int,
    val height: Int,
    val size: Long,
    val dateTaken: Long, // Milliseconds since epoch
    val dateAdded: Long,
    val dateModified: Long,
    val path: String,
    val thumbnailPath: String? = null,
    val locationLat: Double? = null,
    val locationLng: Double? = null,
    val locationName: String? = null,
    val duration: Long? = null, // For videos
    val orientation: Int = 0,
    val isFavorite: Boolean = false,
    val isTrashed: Boolean = false,
    val trashedDate: Long? = null,
    val faceGroupIds: List<Long> = emptyList(),
    val labels: List<String> = emptyList(), // ML labels: "dog", "beach", "food", etc.
    val dominantColors: List<Int> = emptyList(), // ARGB colors
    val blurScore: Float = 1.0f, // 0.0 = blurry, 1.0 = sharp
    val aestheticScore: Float = 0.5f, // 0.0 - 1.0
    val isProcessed: Boolean = false, // For ML processing status
    val version: Int = 1, // For optimistic locking
) {
    val isImage: Boolean
        get() = mimeType.startsWith("image/")

    val isVideo: Boolean
        get() = mimeType.startsWith("video/")


    val aspectRatio: Float
        get() = if (height > 0) width.toFloat() / height else 1.0f
}

@Entity(tableName = "face_groups")
@Serializable
data class FaceGroup(
    @PrimaryKey val id: Long,
    val name: String? = null,
    val coverFaceId: Long? = null,
    val faceCount: Int = 0,
    val createdAt: Long = System.currentTimeMillis(),
    val updatedAt: Long = System.currentTimeMillis(),
    val isHidden: Boolean = false,
    val isNamed: Boolean = false,
)

@Entity(
    tableName = "faces",
    indices = [Index(value = ["mediaItemId"], name = "idx_face_media_item")]
)
@Serializable
data class Face(
    @PrimaryKey val id: Long,
    val mediaItemId: Long,
    val faceGroupId: Long? = null,
    val boundingBox: BoundingBox,
    val embedding: FloatArray? = null, // FaceNet embedding (512-dim)
    val confidence: Float = 1.0f,
    val quality: Float = 1.0f,
    val yaw: Float = 0.0f,
    val pitch: Float = 0.0f,
    val roll: Float = 0.0f,
    val leftEye: PointF? = null,
    val rightEye: PointF? = null,
    val nose: PointF? = null,
    val mouth: PointF? = null,
)

@Serializable
data class BoundingBox(
    val left: Float,
    val top: Float,
    val right: Float,
    val bottom: Float,
) {
    val width: Float get() = right - left
    val height: Float get() = bottom - top
    val centerX: Float get() = (left + right) / 2
    val centerY: Float get() = (top + bottom) / 2
}

@Serializable
data class PointF(val x: Float, val y: Float)

@Entity(tableName = "albums")
@Serializable
data class Album(
    @PrimaryKey val id: Long,
    val title: String,
    val description: String? = null,
    val coverMediaItemId: Long? = null,
    val mediaItemIds: List<Long> = emptyList(),
    val createdAt: Long = System.currentTimeMillis(),
    val updatedAt: Long = System.currentTimeMillis(),
    val isAutoGenerated: Boolean = false,
    val albumType: AlbumType = AlbumType.USER_CREATED,
)

enum class AlbumType {
    USER_CREATED,
    AUTO_PEOPLE,
    AUTO_PLACES,
    AUTO_THINGS,
    AUTO_VIDEOS,
    AUTO_SCREENSHOTS,
    AUTO_DOCUMENTS,
    AUTO_FAVORITES,
    AUTO_RECENT,
    SHARED,
}

@Entity(tableName = "search_history")
@Serializable
data class SearchHistory(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val query: String,
    val timestamp: Long = System.currentTimeMillis(),
    val resultCount: Int = 0,
    val searchType: SearchType = SearchType.TEXT,
)

enum class SearchType {
    TEXT,
    VOICE,
    FACE,
    LOCATION,
    DATE,
    CATEGORY,
    LENS,
}

// Search result with highlighting
@Serializable
data class SearchResult(
    val mediaItems: List<MediaItem>,
    val faceGroups: List<FaceGroup> = emptyList(),
    val albums: List<Album> = emptyList(),
    val suggestions: List<SearchSuggestion> = emptyList(),
    val totalCount: Int,
    val searchTimeMs: Long,
    val appliedFilters: List<SearchFilter> = emptyList(),
)

@Serializable
data class SearchSuggestion(
    val text: String,
    val type: SuggestionType,
    val icon: String? = null,
    val count: Int? = null,
)

enum class SuggestionType {
    RECENT_QUERY,
    PEOPLE,
    PLACE,
    THING,
    DATE_RANGE,
    CATEGORY,
    CREATION,
}

@Serializable
data class SearchFilter(
    val type: FilterType,
    val value: String,
    val label: String,
)

enum class FilterType {
    DATE_RANGE,
    LOCATION,
    PEOPLE,
    MEDIA_TYPE,
    FAVORITES,
    ALBUM,
    CAMERA,
    EDIT_STATUS,
}